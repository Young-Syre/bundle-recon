/*
 * Rebuilds the credential fixture from fragments.
 *
 * test/fixtures/secrets/credentials.js.in is a template. The five values below
 * are the ones hosted secret scanners match on sight, so they are not stored
 * as contiguous literals anywhere in this repository -- not in a fixture, not
 * in a test, not in any commit. They are reassembled here, in memory, at the
 * moment the suite runs.
 *
 * They are still fabricated, still random-looking, and still never valid
 * anywhere. The fragmentation is about the scanner that reads this repository,
 * not about the one this repository implements: bundle-recon applies an
 * entropy floor, so substituting a low-entropy placeholder such as
 * EXAMPLE_FAKE_KEY would make the fixture stop matching -- correctly -- and the
 * rule under test would no longer be exercised.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

/** Placeholder name -> the value the fixture should contain at test time. */
export const FIXTURE_CREDENTIALS: Readonly<Record<string, string>> = {
  __AWS_ACCESS_KEY_ID__: 'AKIA' + '7QJ4MZ2W' + 'NVB3KD5P',
  __AWS_SECRET_ACCESS_KEY__: 'wJz9K3pQ7LmN2vB8' + 'xY4tR6sD1fG5' + 'hJ0kL9cV3nM7',
  __STRIPE_SECRET_KEY__: 'sk_' + 'live_' + '51Nq8ZkD7yTbVrP2wXsHgM4aC',
  __SLACK_BOT_TOKEN__: 'xoxb' + '-2847301923-4918273645091-' + 'Zq7Kd2Mv9Rt4Bn6Xw1Lp8Yc3',
  __TWILIO_ACCOUNT_SID__: 'AC' + '9f3b7c2e5a81' + '4d6098b1c4e7f20a5d83',
};

/**
 * Read a fixture template and substitute every placeholder.
 *
 * Throws if a placeholder survives, so a renamed or mistyped marker fails the
 * suite instead of silently producing a fixture the rules cannot match.
 */
export function credentialsFixturePath(): string {
  return path.resolve(here, '..', '..', 'test', 'fixtures', 'secrets', 'credentials.js');
}

/**
 * Materialise the rendered fixture next to the other fixtures.
 *
 * The integration tests walk the fixture tree from disk, so the rendered file
 * has to exist there. It is generated by the `test` script and excluded by
 * .gitignore, which is the whole point: the assembled values live in a working
 * tree and never in a commit.
 */
export function writeCredentialsFixture(): string {
  const target = credentialsFixturePath();
  const text = renderCredentialsFixture();
  fs.writeFileSync(target, text);
  return target;
}

export function renderCredentialsFixture(): string {
  const template = fs.readFileSync(path.resolve(here, '..', '..', 'test', 'fixtures', 'secrets', 'credentials.js.in'), 'utf8');
  let text = template;
  for (const [marker, value] of Object.entries(FIXTURE_CREDENTIALS)) {
    text = text.split(marker).join(value);
  }
  const leftover = text.match(/__[A-Z0-9_]+__/);
  if (leftover) {
    throw new Error(`credentials fixture still contains the placeholder ${leftover[0]}`);
  }
  return text;
}
